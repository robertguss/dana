//! Self-contained HTML5 and GitHub-flavored Markdown report renderers.

use std::fmt::Write as _;

use crate::oracle::value::{ReportVal, Val};
use crate::viz::svg::render_chart_svg;
use crate::viz::terminal::render_chart_terminal;
use crate::viz::{format_chart_val, xml_escape};

fn is_numeric_val(v: &Val) -> bool {
    match v {
        Val::Int(_) | Val::Decimal(_) | Val::Float(_) => true,
        Val::OptSome(inner) => is_numeric_val(inner),
        _ => false,
    }
}

/// Render a [`ReportVal`] into a rich, self-contained responsive HTML5 document with
/// inline CSS, summary cards, embedded inline `<svg>` charts, and HTML-escaped tables
/// (zero external URLs, zero external scripts).
#[must_use]
pub fn render_html_report(rep: &ReportVal) -> String {
    let safe_title = xml_escape(&rep.title);
    let mut out = String::with_capacity(2048);
    let _ = writeln!(
        out,
        "<!doctype html>\n\
         <html lang=\"en\">\n\
         <head>\n\
         <meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>{safe_title}</title>\n\
         <style>\n\
         :root {{ --bg: #f8fafc; --surface: #ffffff; --ink: #0f172a; --muted: #475569; --border: #e2e8f0; --accent: #2563eb; --accent-soft: #eff6ff; }}\n\
         * {{ box-sizing: border-box; }}\n\
         body {{ margin: 0; padding: 2rem 1rem; background: var(--bg); color: var(--ink); font-family: -apple-system, BlinkMacSystemFont, \"Segoe UI\", Roboto, Helvetica, Arial, sans-serif; line-height: 1.55; }}\n\
         .container {{ max-width: 960px; margin: 0 auto; }}\n\
         header {{ margin-bottom: 1.75rem; padding-bottom: 1rem; border-bottom: 2px solid var(--border); }}\n\
         h1 {{ margin: 0; font-size: 1.85rem; letter-spacing: -0.02em; }}\n\
         .meta {{ margin-top: 0.35rem; font-size: 0.85rem; color: var(--muted); }}\n\
         .summary-card {{ background: var(--accent-soft); border-left: 4px solid var(--accent); border-radius: 8px; padding: 0.9rem 1.15rem; margin-bottom: 1rem; }}\n\
         .summary-card p {{ margin: 0; }}\n\
         .chart-card {{ background: var(--surface); border: 1px solid var(--border); border-radius: 10px; padding: 1rem; margin: 1.25rem 0; box-shadow: 0 1px 2px rgba(15,23,42,0.04); }}\n\
         .chart-card svg {{ width: 100%; height: auto; display: block; }}\n\
         .table-wrap {{ background: var(--surface); border: 1px solid var(--border); border-radius: 10px; overflow-x: auto; margin: 1.25rem 0; box-shadow: 0 1px 2px rgba(15,23,42,0.04); }}\n\
         table {{ width: 100%; border-collapse: collapse; font-size: 0.9rem; }}\n\
         thead th {{ text-align: left; background: #f1f5f9; color: var(--ink); font-weight: 600; padding: 0.65rem 0.85rem; border-bottom: 1px solid var(--border); white-space: nowrap; }}\n\
         tbody td {{ padding: 0.55rem 0.85rem; border-bottom: 1px solid var(--border); }}\n\
         tbody tr:nth-child(even) {{ background: #f8fafc; }}\n\
         tbody tr:last-child td {{ border-bottom: none; }}\n\
         .num {{ text-align: right; font-variant-numeric: tabular-nums; }}\n\
         </style>\n\
         </head>\n\
         <body>\n\
         <main class=\"container\">\n\
         <header>\n\
         <h1>{safe_title}</h1>\n\
         <div class=\"meta\">Generated by Dana Analytics</div>\n\
         </header>"
    );

    for summary in &rep.summaries {
        let _ = writeln!(
            out,
            "<section class=\"summary-card\"><p>{}</p></section>",
            xml_escape(summary)
        );
    }

    for chart in &rep.charts {
        out.push_str("<figure class=\"chart-card\">\n");
        out.push_str(&render_chart_svg(chart));
        out.push_str("</figure>\n");
    }

    for (hdrs, rows) in &rep.tables {
        out.push_str("<div class=\"table-wrap\"><table><thead><tr>");
        for h in hdrs {
            let _ = write!(out, "<th>{}</th>", xml_escape(h));
        }
        out.push_str("</tr></thead><tbody>");
        for row in rows {
            out.push_str("<tr>");
            for cell in row {
                let cls = if is_numeric_val(cell) {
                    " class=\"num\""
                } else {
                    ""
                };
                let _ = write!(out, "<td{cls}>{}</td>", xml_escape(&format_chart_val(cell)));
            }
            out.push_str("</tr>");
        }
        out.push_str("</tbody></table></div>\n");
    }

    out.push_str("</main>\n</body>\n</html>\n");
    out
}

fn escape_md_cell(s: &str) -> String {
    s.replace('|', "\\|").replace('\r', "").replace('\n', " ")
}

/// Render a [`ReportVal`] into clean GitHub-flavored Markdown with title, summaries,
/// chart summaries/previews, and formatted Markdown tables.
#[must_use]
pub fn render_markdown_report(rep: &ReportVal) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# {}\n", rep.title);

    for summary in &rep.summaries {
        let _ = writeln!(out, "> {summary}\n");
    }

    for (idx, chart) in rep.charts.iter().enumerate() {
        let heading = if chart.title.is_empty() {
            format!("Chart {} ({:?})", idx + 1, chart.kind)
        } else {
            chart.title.clone()
        };
        let _ = writeln!(out, "## {heading}\n");
        let _ = writeln!(
            out,
            "- Kind: `{:?}`\n- Columns: `{}`\n- Points: {}",
            chart.kind,
            chart.col_names.join("`, `"),
            chart.series.first().map_or(0, Vec::len)
        );
        if let Some((slope, intercept, r2)) = chart.trendline
            && slope.is_finite()
            && intercept.is_finite()
            && r2.is_finite()
        {
            let sign = if intercept >= 0.0 { "+" } else { "-" };
            let _ = writeln!(
                out,
                "- OLS Trendline: `y = {:.4}x {sign} {:.3}` (R² = {:.3})",
                slope,
                intercept.abs(),
                r2
            );
        }
        out.push_str("\n```text\n");
        out.push_str(&render_chart_terminal(chart));
        out.push_str("\n```\n\n");
    }

    for (hdrs, rows) in &rep.tables {
        if hdrs.is_empty() {
            continue;
        }
        out.push('|');
        for h in hdrs {
            let _ = write!(out, " {} |", escape_md_cell(h));
        }
        out.push('\n');
        out.push('|');
        for _ in hdrs {
            out.push_str(" --- |");
        }
        out.push('\n');
        for row in rows {
            out.push('|');
            for cell in row {
                let _ = write!(out, " {} |", escape_md_cell(&format_chart_val(cell)));
            }
            out.push('\n');
        }
        out.push('\n');
    }

    out
}
